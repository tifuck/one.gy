// Copies the website's own stylesheets and fonts from the repo's static/
// into src/ui/site/ (gitignored, generated) so the sync panel and the offline
// page use the real site CSS instead of hand-kept copies. Runs before start,
// dist and in CI. Font url()s are rewritten to the vendored fonts/ folder;
// @font-face rules whose file the repo does not ship are dropped.
'use strict';

const fs = require('fs');
const path = require('path');

const STATIC = path.join(__dirname, '..', '..', '..', 'static');
const OUT = path.join(__dirname, '..', 'src', 'ui', 'site');
// The stack _app_base.html loads, plus the admin console's layout (admin.css).
const CSS = ['core.css', 'components.css', 'themes.css', 'editorial-base.css', 'app-shell.css', 'context-menu.css', 'ui-v2.css', 'admin.css'];
const FONT_DIRS = ['vendor/fonts', 'fonts'];
const FONT_URL = /url\((['"]?)\/static\/(?:vendor\/)?fonts\/([\w.-]+\.woff2)\1\)/g;

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'fonts'), { recursive: true });

const fonts = new Set();
for (const dir of FONT_DIRS) {
  for (const name of fs.readdirSync(path.join(STATIC, dir))) {
    if (!name.endsWith('.woff2')) continue;
    fs.copyFileSync(path.join(STATIC, dir, name), path.join(OUT, 'fonts', name));
    fonts.add(name);
  }
}

for (const name of CSS) {
  const src = fs.readFileSync(path.join(STATIC, name), 'utf8')
    .replace(/@font-face\{[^}]*\}\n?/g, (rule) => {
      const files = [...rule.matchAll(FONT_URL)].map((m) => m[2]);
      return files.length && files.every((f) => fonts.has(f)) ? rule : '';
    })
    .replace(FONT_URL, (_m, q, file) => `url(${q}fonts/${file}${q})`);
  if (/url\((['"]?)\//.test(src)) throw new Error(`${name}: absolute url() left after rewriting`);
  fs.writeFileSync(path.join(OUT, name), `/* Generated by desktop/app/scripts/vendor-site.js from static/${name}. Do not edit. */\n${src}`);
}

console.log(`[VENDOR] ${CSS.length} stylesheets and ${fonts.size} fonts -> ${path.relative(process.cwd(), OUT) || OUT}`);
